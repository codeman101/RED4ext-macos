#pragma once

#ifdef RED4EXT_PLATFORM_MACOS
#include <cstdint>
#include <filesystem>
#include <optional>
#include <string>
#include <unordered_set>

namespace PluginRequirements
{
// 32-bit constants a plugin dylib can materialize (MOVZ/MOVK pairs, MOVN) or holds in its constant data. Address-DB
// hashes among them are the game addresses the plugin may resolve. Returns nullopt if the file is not a thin 64-bit
// Mach-O that can be parsed safely.
std::optional<std::unordered_set<std::uint32_t>> CollectConstants(const std::filesystem::path& aPath);

// Whether the plugin takes game addresses from RED4ext: it looks up RED4ext_ResolveAddress, or reads the address
// database file itself (RED4ext.SDK 1.0 for macOS). A plugin with neither carries its own address table, so the
// database says nothing about the addresses it uses and the database check does not apply to it.
bool UsesLoaderAddresses(const std::filesystem::path& aPath);

// LOCAL TRIAL PATCH (cp2077-mac R30, a proposal for upstream, not upstream behaviour): "plugins may declare
// self-trapped hashes". A plugin that carries its own address resolver can list, in a sidecar next to it
// (<stem>.trapped-hashes.txt), the address-DB hashes it compiles in but resolves itself to a trap stub or a
// plugin-internal stand-in, never to a game address and never through the database. The sidecar is generated by the
// plugin's build and names the plugin's sha256; a sidecar whose sha256 does not match the plugin file is ignored. The
// gate then accepts a hash only if it is listed AND unverified in the database (a verified hash never needs it);
// nothing in here resolves anything.
struct SelfTrapped
{
    bool present = false; // a sidecar file exists
    bool valid = false;   // it parsed and its sha256 matches the plugin
    std::string reason;   // why it is not valid
    std::unordered_set<std::uint32_t> hashes;
};
SelfTrapped LoadSelfTrapped(const std::filesystem::path& aPluginPath);
} // namespace PluginRequirements
#endif
